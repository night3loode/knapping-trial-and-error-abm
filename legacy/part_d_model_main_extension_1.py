"""
Part D: categories-as-primitives transition model.

Built directly on the untouched base model (see model_main_BASE_reference_only.py in this
same folder, which is never edited). Every line that is NOT part of the Part D extension is
copied verbatim from that base file. Every place that IS new or changed is marked "EXTENSION
(Part D)" in a comment, so a diff against the base file tells you exactly what changed and why.

Spec: "MVP document Part D - transition model (categories as primitives).md" in the Thesis
project. Read that document for the full plain-language + math writeup this file implements.

Summary of what's different from the base model:
  - Agents still hold exactly K ordinary F&S categories -- no schema object, no (K,L) reshape.
    agent.xmeans/ymeans/xsds/ysds/freqs/corrs/labels/age are IDENTICAL in shape and meaning
    to the base model.
  - NEW: each agent also holds `trans`, a (K,K) row-stochastic table. trans[k,k'] is this
    agent's belief "given category k was just used, category k' comes next." Starts uniform.
  - Producing an utterance now produces an ORDERED SEQUENCE of L tokens (L=2 for now, but the
    code takes L as a parameter): the first category is picked by popularity (unchanged F&S
    rule); every category after the first is picked from the previous category's row of
    `trans` instead of by popularity. Each individual token is still generated by F&S's
    unchanged per-signal noise rule.
  - Listening classifies each token in the sequence independently, in order, using F&S's
    UNCHANGED single-token classification+learning math, called once per token (sequential,
    not frozen-batch -- see spec doc D.3/D.6 for why). After all tokens are classified, ONE
    new update rule nudges trans[winner_l, winner_l+1] for each consecutive pair of winners,
    weighted by both winners' posteriors -- explicitly NOT weighted by prestige, which plays
    no role in this model despite being left in place (inert, =1) everywhere else in the file.
"""

