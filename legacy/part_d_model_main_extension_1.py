def run_paramlist(condition_number):
    # EXTENSION (Part D): paramlist rows now carry a trailing L value.
    pop_size_init, end_pop, iterations, doff, sd_init, K, attraction, \
    transmission_error, load_agents, crit, growth_rate, network, L = paramlist[condition_number]

    numpy.random.seed(condition_number)

    run_condition(pop_size_init, end_pop, iterations, doff, sd_init, K,
                  attraction, transmission_error, load_agents, crit, growth_rate, network, condition_number, L)

